      'ざるを得ない': { overview: '表示没有其他现实选择，只能采取某行动，语气正式。', cautions: ['接ない形去掉「ない」再加本句型；「する」例外为「せざるを得ない」。'], specialCases: ['比「なければならない」更突出非本意和无奈。'] },
      'ことになる': { overview: '表示由外部决定、规则或事态发展形成的结果，也可表示从事实推导出的结论。', cautions: ['通常不是说话人主动做出的决定。'], specialCases: ['「ことになった」常说明已经确定的安排。'] },
