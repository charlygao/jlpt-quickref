    if (/Vて|て形/.test(c)) notes.push('前接动词使用て形，五段动词要注意音便。');
    if (/Vた|た形/.test(c)) notes.push('前接动词使用た形；除过去外，也可能表示动作完成后的状态。');
    if (/辞书形|V辞书/.test(c)) notes.push('前接动词使用辞书形，不接「ます」或「です」。');
    if (/意向形/.test(c)) notes.push('前接意向形，如「行こう」「食べよう」「しよう」「来よう」。');
    if (/可能形/.test(c)) notes.push('前接可能形，如「書ける」「食べられる」。');
    if (/Nの/.test(c)) notes.push('名词后需要「の」再连接，除非本条另列其他接续。');
    if (/な形/.test(c)) notes.push('な形容词可能使用「な」「で」「だ」或「である」，应严格按本条公式。');
    if (/い形/.test(c)) notes.push('い形容词应按公式保留「い」或变为「く／くて／かった」。');
    if (/[／/]/.test(c)) notes.push('斜线表示按词类或语义择一使用，不是把所有形式叠加。');
    return notes.length ? uniq(notes) : ['先完成前接词的活用，再连接卡片所列的完整句型。'];
