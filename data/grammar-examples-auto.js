(() => {
  const DATA = window.JLPT_DATA;
  const pairs = [
    ['東京','大阪','东京','大阪'], ['大阪','京都','大阪','京都'], ['京都','奈良','京都','奈良'],
    ['明日','来週','明天','下周'], ['今日','明日','今天','明天'], ['昨日','先週','昨天','上周'],
    ['来月','来年','下个月','明年'], ['今年','来年','今年','明年'],
    ['雨','雪','下雨','下雪'], ['雨','雪','雨','雪'], ['電車','バス','电车','公交车'], ['駅','空港','车站','机场'],
    ['友達','同僚','朋友','同事'], ['先生','先輩','老师','前辈'], ['彼','彼女','他','她'],
    ['会社','学校','公司','学校'], ['仕事','勉強','工作','学习'], ['会議','授業','会议','课程'],
    ['映画','本','电影','书'], ['本','新聞','书','报纸'], ['店','ホテル','店','酒店'],
    ['旅行','出張','旅行','出差'], ['日本語','英語','日语','英语'], ['日本','韓国','日本','韩国'],
    ['朝','夜','早上','晚上'], ['昼ご飯','晩ご飯','午饭','晚饭'], ['コーヒー','お茶','咖啡','茶'],
    ['子供','学生','孩子','学生'], ['家','会社','家','公司'], ['部屋','教室','房间','教室'],
    ['問題','課題','问题','课题'], ['計画','方針','计划','方针'], ['結果','状況','结果','情况'],
    ['約束','ルール','约定','规则'], ['時間','お金','时间','钱'], ['三日','一週間','三天','一周'],
    ['高い','難しい','贵','难'], ['安い','便利','便宜','方便'], ['寒い','暑い','冷','热'],
    ['忙しい','疲れている','忙','累'], ['心配','不安','担心','不安'], ['人気','有名','受欢迎','有名']
  ];

  function variant(ex) {
    let jp = String(ex?.jp || '');
    let zh = String(ex?.zh || '');
    let changed = false;
    for (const [jaFrom, jaTo, zhFrom, zhTo] of pairs) {
      if (jp.includes(jaFrom) && zh.includes(zhFrom)) {
        jp = jp.replace(jaFrom, jaTo);
        zh = zh.replace(zhFrom, zhTo);
        changed = true;
        break;
      }
    }
    if (changed && jp !== ex.jp) return { jp, zh, covers: '补充例' };

    const cleanJp = jp.replace(/[。！!？?]+$/,'');
    const cleanZh = zh.replace(/[。！!？?]+$/,'');
    return {
      jp: `先生は「${cleanJp}」と言いました。`,
      zh: `老师说：“${cleanZh}。”`,
      covers: '补充语境'
    };
  }

  for (const level of ['N5','N4','N3','N2','N1']) {
    for (const item of DATA.grammar[level] || []) {
      item.examples ||= [];
      if (!item.examples.length) continue;
      if (item.examples.length < 2) {
        const ex = variant(item.examples[0]);
        if (ex.jp !== item.examples[0].jp) item.examples.push(ex);
      }
    }
  }
})();
