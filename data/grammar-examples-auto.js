  function inferCover(item, ex) {
    if (ex.covers) return ex.covers;
    const jp = String(ex.jp || '');
    const c = String(item.connection || '').trim();
    if (/ませんでした/.test(jp)) return 'Vませんでした';
    if (/ました[。！？]?$/u.test(jp) && /ました/.test(item.title + c)) return 'Vました';
    if (/ません[。！？]?$/u.test(jp) && /ません/.test(item.title + c)) return 'Vません';
    if (/でした[。！？]?$/u.test(jp) && /でした/.test(item.title + c)) return 'N / な形 + でした';
    if (/ではありません/.test(jp)) return 'N / な形 + ではありません';
    if (/くない/.test(jp) && /い形/.test(c)) return 'い形 + くない';
    if (/かった/.test(jp) && /い形/.test(c)) return 'い形 + かった';
    if (/なので/.test(jp)) return 'N / な形 + なので';
    if (/なのに/.test(jp)) return 'N / な形 + なのに';
    if (/なら/.test(jp) && /なら/.test(c)) return 'N / な形 + なら';
    if (/ているところ/.test(jp)) return 'Vている + ところ';
    if (/たところ/.test(jp) && /ところ/.test(c)) return 'Vた + ところ';
    if (/るところ/.test(jp) && /ところ/.test(c)) return 'V辞书 + ところ';
    if (/そう/.test(jp) && /そう/.test(c)) return c;
    return c || item.title;
  }

